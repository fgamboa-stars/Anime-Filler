import type { Calibration } from '../engine/calibration.js';
import { BACKTEST_MODES, crossFitCalibration, fitFinalCalibration, scoreSamples, type BacktestSample, type ModeReport } from './backtest.js';

export interface BacktestReport {
  generatedAt: string;
  series: number;
  modes: ModeReport[];
  calibration: Calibration;
  decisiveEpisodes: number;
}

export function buildReport(samples: BacktestSample[], seriesCount: number, version: string): BacktestReport {
  const crossFit = crossFitCalibration(samples);
  const confidence = (s: BacktestSample) => crossFit.get(s) ?? 0.99;
  const modes = BACKTEST_MODES.map((mode) => scoreSamples(mode, samples.filter((s) => s.mode === mode), confidence));
  return {
    generatedAt: new Date().toISOString(),
    series: seriesCount,
    modes,
    calibration: fitFinalCalibration(samples, version),
    // The same episodes recur across modes, and some modes only cover part of a series. Cold-start covers all of them.
    decisiveEpisodes: Math.max(...modes.map((m) => m.decisiveExcluded)),
  };
}

const percent = (x: number) => `${(x * 100).toFixed(1)}%`;

const MODE_MEANING: Record<string, string> = {
  'next-episode': 'A new episode arrives after every earlier one was reviewed',
  'gap-fill': 'Random episodes are missing; both neighbours are known',
  'sparse-review': 'A person reviewed one episode in eight; the rest are predicted in airing order',
  'batch-tail': 'The last 30% of a series arrives at once, with nobody reviewing along the way',
  'new-season': 'A new season arrives; only earlier seasons have labels',
  'cold-start': 'A series with no labels and no related seasons',
};

export function renderReport(report: BacktestReport): string {
  const lines: string[] = [
    '# Backtest results',
    '',
    `Generated by \`npm run backtest\` on ${report.generatedAt.slice(0, 10)}, from ${report.series} series of curated labels replayed as if each episode were new.`,
    '',
    'Each mode hides what would not be known at that moment, including arc names, later seasons, and any statistics learned from hidden labels. Confidence bands use out-of-fold calibration: a story group is never scored by a curve fitted on its own episodes.',
    '',
    '## Accuracy against the base rate',
    '',
    '"Always canon" is the baseline: predicting the most common label. Macro F1 weighs all four labels equally, so it exposes a model that ignores the rarer ones.',
    '',
    '| Scenario | What it simulates | Episodes | Accuracy | Always canon | Macro F1 | Baseline F1 |',
    '| --- | --- | ---: | ---: | ---: | ---: | ---: |',
  ];
  for (const m of report.modes) {
    lines.push(
      `| ${m.mode} | ${MODE_MEANING[m.mode]} | ${m.episodes} | ${percent(m.accuracy)} | ${percent(m.baselineAccuracy)} | ${percent(m.macroF1)} | ${percent(m.baselineMacroF1)} |`,
    );
  }
  lines.push(
    '',
    '## What the confidence bands deliver',
    '',
    'Share of episodes in each band, and how often the prediction in that band was right.',
    '',
    '| Scenario | Auto-approve | Right | Suggested | Right | Needs review | Right |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: |',
  );
  for (const m of report.modes) {
    const { AUTO_APPROVED: a, SUGGESTED: s, NEEDS_REVIEW: r } = m.bands;
    const right = (b: typeof a) => (b.episodes > 0 ? percent(b.accuracy) : 'n/a');
    lines.push(`| ${m.mode} | ${percent(a.share)} | ${right(a)} | ${percent(s.share)} | ${right(s)} | ${percent(r.share)} | ${right(r)} |`);
  }
  lines.push(
    '',
    'New-season and cold-start can never auto-approve, by policy. Their bands also carry little meaning: with no labels nearby, the engine predicts canon almost every time, so "right" mostly reflects how much canon a show happens to have.',
    '',
    '## Per label',
    '',
    '| Scenario | Label | Episodes | Precision | Recall |',
    '| --- | --- | ---: | ---: | ---: |',
  );
  for (const m of report.modes) {
    for (const [label, c] of Object.entries(m.perClass)) {
      if (c.support > 0) lines.push(`| ${m.mode} | ${label} | ${c.support} | ${percent(c.precision)} | ${percent(c.recall)} |`);
    }
  }
  lines.push(
    '',
    '## The two costly mistakes',
    '',
    '| Scenario | Filler shown as canon (viewer sits through it) | Canon shown as filler (viewer skips story) |',
    '| --- | ---: | ---: |',
  );
  for (const m of report.modes) lines.push(`| ${m.mode} | ${m.fillerMissedAsCanon} | ${m.canonSkippedAsFiller} |`);
  lines.push(
    '',
    '## Not measured',
    '',
    `- **OVA, Special and Movie.** The datasets have no such labels. AniList format settles those, and the ${report.decisiveEpisodes} episodes in OVA- or Special-format entries are excluded above because their curated labels use a different scheme (for example CANON).`,
    '- **Episodes with descriptions.** AniList has none, so everything here is title and metadata only.',
    '',
  );
  return lines.join('\n');
}
